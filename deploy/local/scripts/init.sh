#!/usr/bin/env bash
# One-time setup of the local stack: writes .env with random secrets, a local CA and the Collector's TLS
# certificate, and the OTLP token file. Safe to re-run: existing files are kept.
#   scripts/init.sh                  create what is missing
#   scripts/init.sh --reissue-cert   new Collector certificate from the same CA, for a changed PUBLIC_HOST
#   scripts/init.sh --force          regenerate everything, secrets and CA included
# The tenant comes from JUICE_PLATFORM_TENANT_ID, or a prompt in a terminal, or defaults to local-dev. It is set once,
# when .env is created.
set -euo pipefail
cd "$(dirname "$0")/.."
export MSYS_NO_PATHCONV=1

force=false
reissue=false
case "${1:-}" in
  "") ;;
  --force) force=true ;;
  --reissue-cert) reissue=true ;;
  *) echo "usage: scripts/init.sh [--force | --reissue-cert]" >&2; exit 1 ;;
esac

secret() { openssl rand -hex 24; }

choose_tenant() {
  local tenant=${JUICE_PLATFORM_TENANT_ID:-}
  if [[ -z "$tenant" && -t 0 ]]; then
    read -rp "Platform tenant id of this deployment [local-dev]: " tenant
  fi
  tenant=${tenant:-local-dev}
  [[ "$tenant" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]] || { echo "invalid tenant id: $tenant" >&2; exit 1; }
  # The integration test Collector stamps this one; sharing it would mix test data into the deployment.
  [[ "$tenant" != local-test ]] || { echo "local-test is reserved for the integration tests" >&2; exit 1; }
  echo "$tenant"
}

# The Collector's certificate, for the addresses clients use: PUBLIC_HOST included, so other machines can send to it.
issue_server_cert() {
  local host san=DNS:localhost,DNS:otel-collector,DNS:otel-collector-test,IP:127.0.0.1
  host=$(grep '^PUBLIC_HOST=' .env | cut -d= -f2- | tr -d '\r')
  if [[ "$host" =~ ^[0-9.]+$ ]]; then
    san+=,IP:$host
  elif [[ -n "$host" && "$host" != localhost ]]; then
    san+=,DNS:$host
  fi
  openssl req -newkey rsa:2048 -nodes -subj "/CN=otel-collector" \
    -keyout secrets/tls/server.key.new -out secrets/tls/server.csr 2>/dev/null
  printf 'subjectAltName=%s\nextendedKeyUsage=serverAuth\n' "$san" > secrets/tls/server.ext
  openssl x509 -req -in secrets/tls/server.csr -CA secrets/tls/ca.crt -CAkey secrets/tls/ca.key -CAcreateserial \
    -days 825 -extfile secrets/tls/server.ext -out secrets/tls/server.crt.new 2>/dev/null
  # The Collector image runs as a non-root user; it must be able to read the key.
  chmod 644 secrets/tls/server.key.new
  mv secrets/tls/server.key.new secrets/tls/server.key
  mv secrets/tls/server.crt.new secrets/tls/server.crt
  rm -f secrets/tls/server.csr secrets/tls/server.ext secrets/tls/ca.srl
  echo "wrote the Collector certificate for $san"
}

mkdir -p secrets/tls backups/clickhouse

if $force || [[ ! -f .env ]]; then
  tenant=$(choose_tenant)
  cat > .env <<EOF
# Generated by scripts/init.sh. Local development only; do not commit.
COMPOSE_PROJECT_NAME=juice-observability

# The one platform tenant of this deployment, stamped on every record by the Collector (requirements §4 step 4).
JUICE_PLATFORM_TENANT_ID=$tenant

# Retention per signal, requirements §9 reference profile (TTL is set when the exporter creates the tables;
# changing it later needs ALTER TABLE ... MODIFY TTL, see README.md).
JUICE_TRACES_TTL=720h
JUICE_METRICS_TTL=2160h
JUICE_LOGS_TTL=720h

CLICKHOUSE_ADMIN_PASSWORD=$(secret)
CLICKHOUSE_OTEL_PASSWORD=$(secret)
CLICKHOUSE_GRAFANA_PASSWORD=$(secret)
CLICKHOUSE_PLATFORM_PASSWORD=$(secret)
GRAFANA_ADMIN_PASSWORD=$(secret)
POSTGRES_PASSWORD=$(secret)
EOF
  echo "wrote .env (tenant $tenant)"
fi

# Keys added after the first version of this script; appended to an existing .env when missing.
ensure() {
  grep -q "^$1=" .env || { echo "$1=$2" >> .env; echo "added $1 to .env"; }
}
ensure KEYCLOAK_ADMIN_PASSWORD "$(secret)"
ensure GRAFANA_OIDC_CLIENT_SECRET "$(secret)"
# Password of the demo users in the local Keycloak realm (README.md lists them).
ensure KEYCLOAK_DEMO_PASSWORD "$(openssl rand -hex 8)"
# Host name or IP that browsers use for the Console, Keycloak and Grafana (README.md, "Another machine").
ensure PUBLIC_HOST localhost

if $force || [[ ! -f secrets/otlp-tokens ]]; then
  {
    echo "$(secret) juice-sample"
  } > secrets/otlp-tokens
  echo "wrote secrets/otlp-tokens"
fi

if $force || [[ ! -f secrets/tls/server.crt ]]; then
  openssl req -x509 -newkey rsa:2048 -nodes -days 825 -subj "/CN=Juice Observability local CA" \
    -keyout secrets/tls/ca.key -out secrets/tls/ca.crt 2>/dev/null
  echo "wrote the local CA"
  issue_server_cert
elif $reissue; then
  [[ -f secrets/tls/ca.key ]] || { echo "no secrets/tls/ca.key: this certificate comes from another CA" >&2; exit 1; }
  issue_server_cert
  echo "restart the Collector to use it: docker compose restart otel-collector"
fi

# Juice Agent (roadmap Phase 7): a CA of its own for agent client certificates, the key that signs commands (kept apart from
# it), and the platform's agent listener certificate from the local CA above, so an agent trusts secrets/tls/ca.crt for it.
issue_agent_listener_cert() {
  local host san=DNS:localhost,DNS:platform-api,IP:127.0.0.1
  host=$(grep '^PUBLIC_HOST=' .env | cut -d= -f2- | tr -d '\r')
  if [[ "$host" =~ ^[0-9.]+$ ]]; then san="$san,IP:$host"; elif [[ "$host" != localhost ]]; then san="$san,DNS:$host"; fi
  openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out secrets/agents/listener.key 2>/dev/null
  openssl req -new -key secrets/agents/listener.key -subj "/CN=platform-api" -out secrets/agents/listener.csr 2>/dev/null
  printf 'subjectAltName=%s\nextendedKeyUsage=serverAuth\n' "$san" > secrets/agents/listener.ext
  openssl x509 -req -in secrets/agents/listener.csr -CA secrets/tls/ca.crt -CAkey secrets/tls/ca.key -CAcreateserial \
    -days 825 -extfile secrets/agents/listener.ext -out secrets/agents/listener.crt 2>/dev/null
  rm -f secrets/agents/listener.csr secrets/agents/listener.ext secrets/tls/ca.srl
  echo "wrote the agent listener certificate for $san"
}

mkdir -p secrets/agents
if $force || [[ ! -f secrets/agents/ca.crt ]]; then
  openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out secrets/agents/ca.key 2>/dev/null
  openssl req -x509 -new -key secrets/agents/ca.key -days 825 -subj "/CN=Juice Observability local agent CA" \
    -addext basicConstraints=critical,CA:TRUE -addext keyUsage=critical,keyCertSign,cRLSign -out secrets/agents/ca.crt 2>/dev/null
  openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out secrets/agents/command.key 2>/dev/null
  echo "wrote the agent CA and the command signing key"
  issue_agent_listener_cert
elif $reissue; then
  issue_agent_listener_cert
fi
# The agent CA key mints agent identities and the command key signs commands every agent obeys: readable by their owner only. The platform
# container runs as this same user (JUICE_UID in .env, docker-compose.yml), so it can still read them through its read-only mount.
chmod 600 secrets/agents/*.key

# A release key for agent packages (agent.update), kept apart from the agent CA and the command key. Only release.pub is mounted, into the
# platform and the agent; release.key signs packages on this machine (console/e2e/agent-update.mjs). In production it stays offline.
mkdir -p secrets/release
if $force || [[ ! -f secrets/release/release.key ]]; then
  openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out secrets/release/release.key 2>/dev/null
  openssl pkey -in secrets/release/release.key -pubout -out secrets/release/release.pub 2>/dev/null
  chmod 600 secrets/release/release.key
  echo "wrote the agent release key"
fi
mkdir -p packages
ensure JUICE_UID "$(id -u)"
